(function () {
  const MEMBERS_KEY = "mr_members_v3";
  const defaults = JSON.parse(JSON.stringify(window.MR_DATA.members));
  try {
    localStorage.removeItem("mr_members_v1");
    localStorage.removeItem("mr_members_v2");
  } catch (error) { /* ignore */ }

  function assetUrl(file, base) {
    if (!file) return "";
    const root = base == null ? "." : base;
    return `${root}/` + String(file).split("/").map(encodeURIComponent).join("/");
  }

  function slugify(name) {
    return String(name || "")
      .toLowerCase()
      .trim()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "") || ("member-" + Date.now());
  }

  function initials(name) {
    const parts = String(name || "").trim().split(/\s+/).filter(Boolean);
    if (!parts.length) return "MR";
    if (parts.length === 1) return parts[0].slice(0, 2).toUpperCase();
    return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
  }

  function normalizeMember(raw, existingSlug) {
    const name = String(raw.name || "").trim();
    const slug = existingSlug || raw.slug || slugify(name);
    const highlights = Array.isArray(raw.highlights)
      ? raw.highlights.map((item) => String(item).trim()).filter(Boolean)
      : String(raw.highlights || "")
          .split(",")
          .map((item) => item.trim())
          .filter(Boolean);

    let stats = Array.isArray(raw.stats) ? raw.stats : [];
    if (!stats.length) {
      stats = [
        { label: "Squad", value: raw.squad || "First Team" },
        { label: "Role", value: raw.role || "Player" },
        { label: "Number", value: raw.number || "—" }
      ];
    }

    return {
      slug,
      name,
      shortName: String(raw.shortName || initials(name)).slice(0, 3).toUpperCase(),
      role: String(raw.role || "Player").trim(),
      squad: String(raw.squad || "First Team").trim(),
      number: String(raw.number || "—").trim() || "—",
      status: String(raw.status || "Active").trim(),
      photo: String(raw.photo || "").trim(),
      bio: String(raw.bio || "").trim(),
      highlights: highlights.length ? highlights : ["Squad member"],
      stats
    };
  }

  function readStored() {
    try {
      const raw = localStorage.getItem(MEMBERS_KEY);
      if (!raw) return null;
      const parsed = JSON.parse(raw);
      return Array.isArray(parsed) ? parsed.map((item) => normalizeMember(item)) : null;
    } catch (error) {
      return null;
    }
  }

  function writeStored(members) {
    localStorage.setItem(MEMBERS_KEY, JSON.stringify(members));
  }

  function syncPublic() {
    window.MR_DATA.members = getMembers();
  }

  function getMembers() {
    return readStored() || JSON.parse(JSON.stringify(defaults));
  }

  function saveMembers(members) {
    const normalized = members.map((item) => normalizeMember(item, item.slug));
    writeStored(normalized);
    syncPublic();
    return normalized;
  }

  function upsertMember(payload, slug) {
    const members = getMembers();
    const index = slug ? members.findIndex((item) => item.slug === slug) : -1;
    const next = normalizeMember(payload, slug || undefined);

    if (index >= 0) {
      const taken = members.some((item, i) => i !== index && item.slug === next.slug);
      if (taken) next.slug = slugify(next.name + "-" + Date.now());
      members[index] = next;
    } else {
      if (members.some((item) => item.slug === next.slug)) {
        next.slug = slugify(next.name + "-" + Date.now());
      }
      members.push(next);
    }

    return saveMembers(members);
  }

  function deleteMember(slug) {
    return saveMembers(getMembers().filter((item) => item.slug !== slug));
  }

  function resetMembers() {
    localStorage.removeItem(MEMBERS_KEY);
    syncPublic();
    return getMembers();
  }

  window.MR_STORE = {
    getMembers,
    saveMembers,
    upsertMember,
    deleteMember,
    resetMembers,
    normalizeMember,
    slugify,
    initials,
    assetUrl
  };

  syncPublic();
})();
